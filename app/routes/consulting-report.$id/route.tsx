// --- Loader ---
export const loader: LoaderFunction = async ({ request, params }: { request: Request, params: Params }) => {
    try {
        const user = await requireUserSession(request);
        if (!user || !user.organisationId) return redirect('/auth');
        if (!params.id) throw new Response("Assessment ID Required", { status: 404 });
        const url = new URL(request.url);

        console.log(`[Consulting Report Loader] User: ${user.organisationId}, Engine: ${params.id}`);

        const { getEnginePaymentStatus, getEngineAccessStatus } = await import("~/models/payment.model.server");
        const isAdmin = (user as any).role === "ADMIN";

        // Check if this is a free assessment (onboarding)
        const isFreeEngine = params.id === "Profiling Assessment";

        // Get detailed payment status
        const paymentStatusResult = isFreeEngine ? { status: "paid" } : await getEnginePaymentStatus(user.organisationId, params.id || "");
        const accessStatus = isFreeEngine
            ? null
            : await getEngineAccessStatus(user.organisationId, params.id || "");
        
        const isPaid = isAdmin || isFreeEngine || paymentStatusResult.status === "paid";
        const isPending = !isPaid && paymentStatusResult.status === "pending";

        console.log(`[Consulting Report Loader] Payment Status - isPaid: ${isPaid}, isPending: ${isPending}, isAdmin: ${isAdmin}`);

        if (!isPaid) {
            if (isPending || paymentStatusResult.status === "rejected") {
                return json({ paymentStatus: paymentStatusResult.status });
            }

            // Redirect to payment: Add to cart with employee-based pricing
            const companyForPrice = await getCompanyProfile(user.organisationId);
            const employeeCount = companyForPrice?.employee_count || 100;

            const engineTypeMap: Record<string, any> = {
                "HR Transformation Roadmap Generator": "roadmap",
                "HCM Vendor Fit Engine": "hcm-vendor-fit",
                "Shared Service Designer": "shared-services",
                "Intelligent Change Management": "icms",
                "HR Technology Maturity Analysis": "hcm-vendor-fit",
                "Digital Maturity Engine": "ai-maturity",
                "AI Driven Maturity Engine": "ai-maturity",
            };
            const engineType = engineTypeMap[params.id || ""] || "hcm-vendor-fit";
            const pricingResult = calculatePricing({ engine: engineType, employeeCount });

            await addOrUpdateCartItem({
                companyId: user.organisationId,
                productName: params.id || "",
                price: pricingResult.totalPrice,
                userId: user.userId,
            });
            return redirect('/cartDashboard');
        }

        if (!isAdmin && accessStatus && !accessStatus.reportUnlocked) {
            return json({ paymentStatus: "partial", pendingAmount: accessStatus.pendingAmount });
        }

        // FIX: Don't add COMPANY# prefix - getLatestAnalysis already does this
        const data = await getLatestAnalysis(user.organisationId, params.id);

        console.log(`[Consulting Report Loader] Data found: ${!!data}`);

        if (!data) {
            console.error(`[Consulting Report Loader] No assessment data found for ${params.id}`);
            if (url.searchParams.get("verify") === "true") {
                throw new Response("No assessment data found", { status: 404 });
            }

            const promptMap: Record<string, string> = {
                "Profiling Assessment": "digital_maturity",
                "Digital Maturity Assessment": "digital_maturity",
                "HR Technology Maturity Analysis": "digital_maturity",
                "HR Tech Maturity Analysis": "digital_maturity",
                "Shared Service Designer": "shared_services",
                "Intelligent Change Management": "change_management",
                "Change Management Readiness": "change_management",
                "HCM Vendor Fit Engine": "vendor_fit",
                "HR Transformation Roadmap Generator": "digital_roadmap"
            };

            const promptId = promptMap[params.id || ""] || "digital_maturity";
            return redirect(`/intermediate?engine=${encodeURIComponent(params.id || "Profiling Assessment")}&promptId=${encodeURIComponent(promptId)}&skipQuestions=true`);
        }

        const company_info = await getCompanyProfile(user.organisationId);
        const brand_name = company_info?.brand_name || company_info?.company_name || "Confidential Client";

        // Also fetch raw responses and questions (best-effort; should not fail report rendering)
        let responses = null;
        let questions = null;
        try {
            responses = await getAnswerSheetByAssessmentName(user.organisationId, params.id || "");
            questions = await getLatestQuestion(params.id || "");
        } catch (auxError) {
            console.error("[Consulting Report Loader] Failed to fetch responses/questions:", auxError);
        }

        // Check URL for report type (detailed vs standard)
        const reportType = url.searchParams.get('type') as 'detailed' | 'standard' || 'detailed';

        return json({
            data,
            brand_name,
            companyLogo: company_info?.logo_url,
            assessmentId: params.id || "Unknown Assessment",
            reportType,
            responses,
            questions
        });
    } catch (e) {
        console.error("REPORT_LOADER_ERROR:", e);
        if (e instanceof Response) {
            throw e;
        }
        const errorMessage = e instanceof Error ? e.message : "Unknown error";
        throw new Response(`Internal Server Error: ${errorMessage}`, { status: 500 });
    }
}

interface LoaderReturn {
    data?: DatabaseRecord,
    brand_name?: string,
    companyLogo?: string,
    assessmentId?: string,
    paymentStatus?: string,
    pendingAmount?: number,
    reportType?: 'detailed' | 'standard',
    responses?: any,
    questions?: any
}

// --- Action ---
export const action: ActionFunction = async ({ request, params }) => {
    const user = await requireUserSession(request);
    if (!user || !user.organisationId) return json({ error: "Unauthorized" }, { status: 401 });

    const body = await request.json();
    const engineId = params.id;

    if (body.intent === "generate_report") {
        console.log(`[Consulting Report Action] Generating report for: ${engineId}`);

        // Construct aggregated data for AI
        const engineTypeMap: Record<string, string> = {
            "Intelligent Change Management": "changeManagement",
            "Shared Service Designer": "sharedServices",
            "HCM Vendor Fit Engine": "vendorFit",
            "HR Transformation Roadmap Generator": "sharedServices", // Roadmap uses sharedServices logic for now
            "HR Technology Maturity Analysis": "sharedServices",
            "HR Tech Maturity Analysis": "sharedServices"
        };

        const engineType = engineTypeMap[engineId || ""] || "sharedServices";

        const aggregatedData = {
            companyId: user.organisationId,
            timestamp: new Date().toISOString(),
            engines: {
                [engineType]: {
                    engineName: engineId,
                    progress: 100,
                    responses: body.answers || {},
                    scores: {},
                    aiAnalysis: {}
                }
            },
            completedEnginesCount: 1,
            totalEngines: 1
        };

        try {
            const advisory = await generateHTIAdvisory(aggregatedData as any, engineType as any);
            await saveAdvisoryReport(
                user.organisationId,
                user.userId,
                advisory,
                aggregatedData as any
            );
            return json({ success: true, advisory });
        } catch (error) {
            console.error("AI Generation Error in Consulting Report:", error);
            return json({ error: "Failed to generate AI report" }, { status: 500 });
        }
    }

    return json({ error: "Invalid intent" }, { status: 400 });
};

