// --- Loader ---
export const loader: LoaderFunction = async ({ request, params }: { request: Request, params: Params }) => {
    try {
        const user = await requireUserSession(request);
        if (!user || !user.organisationId) return redirect('/auth');
        if (!params.id) throw new Response("Assessment ID Required", { status: 404 });

        console.log(`[Consulting Report Loader] User: ${user.organisationId}, Engine: ${params.id}`);

        const allPayments = await getCompanyPayments(user.organisationId);
        const isAdmin = (user as any).role === "ADMIN";

        // Check if this is a free assessment (onboarding)
        const isFreeEngine = params.id === "Profiling Assessment" ||
            params.id === "Digital Maturity Assessment" ||
            params.id === "HR Technology Maturity Analysis" ||
            params.id === "HR Tech Maturity Analysis";

        // Check if any payment record for this engine is verified
        const isPaid = isAdmin || isFreeEngine || allPayments.some((p: any) =>
            p.status === "payment_verified" &&
            p.items?.some((i: any) => i.engineName.trim() === params.id?.trim())
        );

        // Check if any payment record for this engine is pending (submitted but not verified)
        const isPending = !isPaid && !isFreeEngine && allPayments.some((p: any) =>
            p.status === "payment_submitted" &&
            p.items?.some((i: any) => i.engineName.trim() === params.id?.trim())
        );

        console.log(`[Consulting Report Loader] Payment Status - isPaid: ${isPaid}, isPending: ${isPending}, isAdmin: ${isAdmin}`);

        if (!isPaid && !isAdmin) {
            if (isPending) {
                return json({ paymentStatus: "pending" });
            }

            // Redirect to payment: Add to cart first then checkout
            const price = getEnginePriceByName(params.id);
            await addOrUpdateCartItem({
                companyId: user.organisationId,
                productName: params.id,
                price: price,
                userId: user.userId,
            });
            return redirect('/payment/checkout');
        }

        // FIX: Don't add COMPANY# prefix - getLatestAnalysis already does this
        const data = await getLatestAnalysis(user.organisationId, params.id);

        console.log(`[Consulting Report Loader] Data found: ${!!data}`);

        if (!data) {
            console.error(`[Consulting Report Loader] No assessment data found for ${params.id}`);
            throw new Response("No assessment data found", { status: 404 });
        }

        const company_info = await getCompanyProfile(user.organisationId);
        const brand_name = company_info?.brand_name || company_info?.company_name || "Confidential Client";

        // Also fetch raw responses and questions
        const responses = await getAnswerSheetByAssessmentName(user.organisationId, params.id || "");
        const questions = await getLatestQuestion(params.id || "");

        // Check URL for report type (detailed vs standard)
        const url = new URL(request.url);
        const reportType = url.searchParams.get('type') as 'detailed' | 'standard' || 'detailed';

        return json({
            data,
            brand_name,
            companyLogo: company_info?.logo_url,
            assessmentId: params.id || "Unknown Assessment",
            reportType,
            responses,
            questions
        });
    } catch (e) {
        console.error("REPORT_LOADER_ERROR:", e);
        // Provide more context in the error response if possible
        const errorMessage = e instanceof Error ? e.message : "Unknown error";
        throw new Response(`Internal Server Error: ${errorMessage}`, { status: 500 });
    }
}

interface LoaderReturn {
    data?: DatabaseRecord,
    brand_name?: string,
    companyLogo?: string,
    assessmentId?: string,
    paymentStatus?: string,
    reportType?: 'detailed' | 'standard',
    responses?: any,
    questions?: any
}

// --- Action ---
export const action: ActionFunction = async ({ request, params }) => {
    const user = await requireUserSession(request);
    if (!user || !user.organisationId) return json({ error: "Unauthorized" }, { status: 401 });

    const body = await request.json();
    const engineId = params.id;

    if (body.intent === "generate_report") {
        console.log(`[Consulting Report Action] Generating report for: ${engineId}`);

        // Construct aggregated data for AI
        const engineTypeMap: Record<string, string> = {
            "Intelligent Change Management": "changeManagement",
            "Shared Service Designer": "sharedServices",
            "HCM Vendor Fit Engine": "vendorFit",
            "HR Transformation Roadmap Generator": "sharedServices", // Roadmap uses sharedServices logic for now
            "HR Technology Maturity Analysis": "sharedServices",
            "HR Tech Maturity Analysis": "sharedServices"
        };

        const engineType = engineTypeMap[engineId || ""] || "sharedServices";

        const aggregatedData = {
            companyId: user.organisationId,
            timestamp: new Date().toISOString(),
            engines: {
                [engineType]: {
                    engineName: engineId,
                    progress: 100,
                    responses: body.answers || {},
                    scores: {},
                    aiAnalysis: {}
                }
            },
            completedEnginesCount: 1,
            totalEngines: 1
        };

        try {
            const advisory = await generateHTIAdvisory(aggregatedData as any, engineType as any);
            await saveAdvisoryReport(
                user.organisationId,
                user.userId,
                advisory,
                aggregatedData as any
            );
            return json({ success: true, advisory });
        } catch (error) {
            console.error("AI Generation Error in Consulting Report:", error);
            return json({ error: "Failed to generate AI report" }, { status: 500 });
        }
    }

    return json({ error: "Invalid intent" }, { status: 400 });
};

