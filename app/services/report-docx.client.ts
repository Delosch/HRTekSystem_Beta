import { Document, Packer, Paragraph, TextRun, HeadingLevel, AlignmentType, BorderStyle } from 'docx';
import { saveAs } from 'file-saver';

interface ReportData {
    companyName: string;
    engineName: string;
    generatedDate: string;
    result: any;
}

/**
 * Generate DOCX report from analysis data
 */
export async function generateDOCXReport(reportData: ReportData): Promise<Blob> {
    const sections: any[] = [];

    // Title
    sections.push(
        new Paragraph({
            text: 'AI-Generated Report',
            heading: HeadingLevel.TITLE,
            alignment: AlignmentType.CENTER,
            spacing: { after: 200 },
        })
    );

    sections.push(
        new Paragraph({
            text: reportData.engineName,
            heading: HeadingLevel.HEADING_2,
            alignment: AlignmentType.CENTER,
            spacing: { after: 400 },
        })
    );

    // Company Information
    sections.push(
        new Paragraph({
            children: [
                new TextRun({ text: 'Company: ', bold: true }),
                new TextRun({ text: reportData.companyName }),
            ],
            spacing: { after: 100 },
        })
    );

    sections.push(
        new Paragraph({
            children: [
                new TextRun({ text: 'Generated: ', bold: true }),
                new TextRun({
                    text: new Date(reportData.generatedDate).toLocaleDateString('en-IN', {
                        day: 'numeric',
                        month: 'long',
                        year: 'numeric',
                        hour: '2-digit',
                        minute: '2-digit',
                    }),
                }),
            ],
            spacing: { after: 400 },
        })
    );

    // Divider
    sections.push(
        new Paragraph({
            border: {
                bottom: {
                    color: 'CCCCCC',
                    space: 1,
                    style: BorderStyle.SINGLE,
                    size: 6,
                },
            },
            spacing: { after: 300 },
        })
    );

    // Report Content
    sections.push(
        new Paragraph({
            text: 'Analysis Report',
            heading: HeadingLevel.HEADING_1,
            spacing: { after: 200 },
        })
    );

    // Process report data
    if (reportData.result && typeof reportData.result === 'object') {
        Object.entries(reportData.result).forEach(([key, value]) => {
            // Section title
            const sectionTitle = key.replace(/_/g, ' ').replace(/\b\w/g, l => l.toUpperCase());
            sections.push(
                new Paragraph({
                    text: sectionTitle,
                    heading: HeadingLevel.HEADING_2,
                    spacing: { before: 200, after: 100 },
                })
            );

            // Section content
            if (typeof value === 'object' && value !== null) {
                if (Array.isArray(value)) {
                    value.forEach((item, index) => {
                        const text = typeof item === 'object' ? JSON.stringify(item, null, 2) : String(item);
                        sections.push(
                            new Paragraph({
                                children: [
                                    new TextRun({ text: `${index + 1}. `, bold: true }),
                                    new TextRun({ text }),
                                ],
                                spacing: { after: 100 },
                            })
                        );
                    });
                } else {
                    Object.entries(value).forEach(([subKey, subValue]) => {
                        const subTitle = subKey.replace(/_/g, ' ').replace(/\b\w/g, l => l.toUpperCase());
                        sections.push(
                            new Paragraph({
                                children: [
                                    new TextRun({ text: `${subTitle}: `, bold: true }),
                                    new TextRun({
                                        text: typeof subValue === 'object' ? JSON.stringify(subValue, null, 2) : String(subValue),
                                    }),
                                ],
                                spacing: { after: 100 },
                            })
                        );
                    });
                }
            } else {
                sections.push(
                    new Paragraph({
                        text: String(value),
                        spacing: { after: 200 },
                    })
                );
            }
        });
    }

    // Footer
    sections.push(
        new Paragraph({
            text: 'Generated by HR-Tek AI Platform',
            alignment: AlignmentType.CENTER,
            spacing: { before: 400 },
        })
    );

    const doc = new Document({
        sections: [
            {
                properties: {},
                children: sections,
            },
        ],
    });

    return await Packer.toBlob(doc);
}

/**
 * Download DOCX report
 */
export async function downloadDOCX(reportData: ReportData, filename?: string) {
    const blob = await generateDOCXReport(reportData);
    const fileName = filename || `${reportData.engineName.replace(/\s+/g, '_')}_Report_${new Date().toISOString().split('T')[0]}.docx`;
    saveAs(blob, fileName);
}
